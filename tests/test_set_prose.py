def page(number: int, rows: Sequence[tuple], width: float, height: float) -> PageGeometry:
    """Rows are `(idx, text, x0, x1, y, size, font)`; each line is one pdf.js item."""
    lines = tuple(
        Line(idx=idx, text=text, x0=x0, x1=x1, y=y, size=size, font=font,
             items=(idx,), item_x=(x0,), item_text=(text,), item_size=(size,))
        for idx, text, x0, x1, y, size, font in rows
    )
    return PageGeometry(page=number, width=width, height=height, lines=lines)


def kind_of(blocks: Sequence[Block], idx: int) -> str:
    return next(b.kind for b in blocks if idx in b.line_ids)


